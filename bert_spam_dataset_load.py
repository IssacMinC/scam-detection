import tensorflow as tf
from transformers import BertTokenizer, TFBertForSequenceClassification
import numpy as np
import pandas as pd
import re
import nltk
from nltk.corpus import stopwords
from nltk.stem import PorterStemmer

nltk.download('stopwords')
tokenizer = BertTokenizer.from_pretrained('bert-base-uncased')
max_len = 512

model = tf.keras.models.load_model('bert_spam_dataset_model', custom_objects={'TFBertForSequenceClassification': TFBertForSequenceClassification})

def clean_email_body(text):
    if not text is str:
      text = str(text)
    text = text.lower()
    text = re.sub(r'<.*?>', '<HTML>', text)
    text = re.sub(r'http\S+|www\S+|https\S+', '<URL>', text)
    text = re.sub(r'\S+@\S+', '<EMAIL>', text)
    text = re.sub(r'[^a-z\s]', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    # remove stopwords
    stop_words = set(stopwords.words('english'))
    text = ' '.join([word for word in text.split() if word not in stop_words])
    # word stemming
    ps = PorterStemmer()
    text = ' '.join([ps.stem(word) for word in text.split()])
    return text

def predict_email(text): # get probability of scam
    cleaned_text = clean_email_body(text)
    inputs = tokenizer(
        cleaned_text,
        max_length=max_len,
        padding='max_length',
        truncation=True,
        return_tensors='tf'
    )
    outputs = model(inputs)
    logit = outputs.logits[0][0].numpy()
    prob = tf.sigmoid(logit).numpy()
    label = 1 if prob >= 0.5 else 0
    label_map = {0: 'not scam', 1: 'scam'}
    print(f"Email: {text}\nPredicted: {label_map[label]} (prob={prob:.2f})")
    return float(prob)

test_email = "Msg Okay Hey there darling it's been 3 week's now and no word back! I'd like some fun you up for it still? Tb ok! XxX std chgs to send, å£1.50 to rcv"
predict_email(test_email)