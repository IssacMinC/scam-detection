import tensorflow as tf
from transformers import BertTokenizer, TFBertForSequenceClassification
from sklearn.model_selection import train_test_split

import pandas as pd
import re
import nltk
nltk.download('stopwords')
from nltk.corpus import stopwords
from nltk.stem import PorterStemmer
from sklearn.model_selection import train_test_split

df = pd.read_csv('spam.csv', encoding='latin-1')
print(df.head())
print(df['v2'][0])


def clean_email_body(text):
    if not text is str:
      text = str(text)
    # Lowercase
    text = text.lower()
    # Remove HTML tags
    text = re.sub(r'<.*?>', '<HTML>', text)
    # Remove URLs
    text = re.sub(r'http\S+|www\S+|https\S+', '<URL>', text)
    # Remove email addresses
    text = re.sub(r'\S+@\S+', '<EMAIL>', text)
    # Remove punctuation and numbers
    text = re.sub(r'[^a-z\s]', '', text)
    # Remove extra whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    # Remove stopwords
    stop_words = set(stopwords.words('english'))
    text = ' '.join([word for word in text.split() if word not in stop_words])
    # Stemming
    ps = PorterStemmer()
    text = ' '.join([ps.stem(word) for word in text.split()])
    return text

df['v2'] = df['v2'].apply(clean_email_body)
df['v1'] = df['v1'].map({'spam': 1, 'ham': 0})

X_train, X_test, y_train, y_test = train_test_split(df['v2'], df['v1'], test_size=0.2)

tokenizer = BertTokenizer.from_pretrained('bert-base-uncased')
max_len = 512

X_train_enc = tokenizer.batch_encode_plus(
    X_train.astype(str).tolist(), # Convert the Series to a list of strings
    max_length=max_len,
    padding='max_length',
    truncation=True,
    return_tensors='tf'
)
X_test_enc = tokenizer.batch_encode_plus(
    X_test.astype(str).tolist(),  # Convert the Series to a list of strings
    max_length=max_len,
    padding='max_length',
    truncation=True,
    return_tensors='tf'
)

model = TFBertForSequenceClassification.from_pretrained('bert-base-uncased', num_labels=1)

optimizer = tf.keras.optimizers.Adam(learning_rate=2e-5)
loss = tf.keras.losses.BinaryCrossentropy(from_logits=True)
metrics = [tf.keras.metrics.SparseCategoricalAccuracy('accuracy')]

model.compile(optimizer=optimizer, loss=loss, metrics=metrics)

history = model.fit(
    x={
        'input_ids': X_train_enc['input_ids'],
        'attention_mask': X_train_enc['attention_mask'],
        'token_type_ids': X_train_enc['token_type_ids']
    },
    y=y_train,
    validation_split=0.1,
    epochs=2,
    batch_size=16
)

test_loss, test_accuracy = model.evaluate(
    x={
        'input_ids': X_test_enc['input_ids'],
        'attention_mask': X_test_enc['attention_mask'],
        'token_type_ids': X_test_enc['token_type_ids']
    },
    y=y_test
)
print(f'Test loss: {test_loss}, Test accuracy: {test_accuracy}')

model.save('bert_spam_dataset_model', save_format='tf')
